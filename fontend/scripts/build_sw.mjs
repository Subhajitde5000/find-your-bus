function main() {
  if (!existsSync(OUT)) {
    console.error(`build_sw: ${OUT} does not exist. Run "next build" first.`);
    process.exit(1);
  }
  const { urls, total, skipped, files } = collect();
  if (!urls.length) {
    console.error("build_sw: nothing to precache. Did next build succeed?");
    process.exit(1);
  }

  // The version is a hash of the files' contents, so an unchanged build does not
  // invalidate everyone's cache, and a changed one always does.
  const hash = createHash("sha256");
  for (const url of urls) {
    const file = join(OUT, url.replace(/^\/+/, "").split("/").join(sep));
    try {
      hash.update(readFileSync(file));
    } catch (error) {
      console.error(`build_sw: cannot read ${file}: ${error.message}`);
      process.exit(1);
    }
    hash.update(url);
  }
  const version = hash.digest("hex").slice(0, 12);

  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, "sw.js"), serviceWorkerSource(urls, version), "utf8");
  writeFileSync(join(OUT, "offline.html"), OFFLINE_HTML, "utf8");

  // Public files are copied into out/ by Next, so the manifest is already there.
  if (!existsSync(join(OUT, "manifest.webmanifest")) && existsSync(join(PUBLIC, "manifest.webmanifest"))) {
    writeFileSync(join(OUT, "manifest.webmanifest"), readFileSync(join(PUBLIC, "manifest.webmanifest")));
  }

  console.log(`build_sw: precaching ${urls.length} of ${files} files (${(total / 1024 / 1024).toFixed(2)} MB, ${skipped} too large)`);
  console.log(`build_sw: wrote out/sw.js as version ${version}`);
}

main();
