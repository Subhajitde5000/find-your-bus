#!/usr/bin/env node
/**
 * Writes the two lookup tables the private QR studio needs.
 *
 * `qr-admin/` is deliberately not part of the website build: it is a private tool that
 * runs from a folder (or behind your own password) and prints stickers. It must work
 * with no internet and no server, so the route and stop lists are generated here once
 * from the same bundle the site ships, and loaded as plain <script> files.
 *
 * Run after rebuilding the timetable data:
 *   cd fontend && node scripts/export-qr-admin-data.mjs
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fontendRoot = resolve(here, "..");
const repoRoot = resolve(fontendRoot, "..");
const datasetPath = join(fontendRoot, "src", "data", "kolkata-bus-data.json");
const outDir = join(repoRoot, "qr-admin", "data");

const dataset = JSON.parse(readFileSync(datasetPath, "utf8"));
const rawRoutes = Array.isArray(dataset.routes) ? dataset.routes : [];
const rawStops = Array.isArray(dataset.stops) ? dataset.stops : [];

if (!rawRoutes.length || !rawStops.length) {
  console.error(`export-qr-admin-data: ${datasetPath} has no routes or stops; nothing written.`);
  process.exit(1);
}

const busCount = new Map();
for (const route of rawRoutes) {
  const seen = new Set();
  for (const stop of route.stops ?? []) {
    if (seen.has(stop)) continue;
    seen.add(stop);
    busCount.set(stop, (busCount.get(stop) ?? 0) + 1);
  }
}

const routes = rawRoutes
  .map((route) => ({
    number: String(route.number),
    origin: String(route.origin ?? ""),
    destination: String(route.destination ?? ""),
    type: String(route.type ?? "Non-AC"),
    operator: String(route.operator ?? ""),
    source: String(route.source ?? ""),
    stops: Array.isArray(route.stops) ? route.stops.length : 0,
    stopsList: Array.isArray(route.stops) ? route.stops : [],
  }))
  .sort((a, b) => a.number.localeCompare(b.number, "en", { numeric: true, sensitivity: "base" }));

const stops = rawStops
  .map((stop) => ({
    name: String(stop.name),
    located: typeof stop.lat === "number" && typeof stop.lng === "number",
    buses: busCount.get(stop.name) ?? 0,
  }))
  .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));

const banner = `/* Generated by fontend/scripts/export-qr-admin-data.mjs from src/data/kolkata-bus-data.json.\n   Do not edit by hand; re-run the script after rebuilding the timetable data. */\n`;

mkdirSync(outDir, { recursive: true });

writeFileSync(
  join(outDir, "routes.js"),
  `${banner}window.QR_ROUTES = ${JSON.stringify(routes)};\nwindow.QR_META = ${JSON.stringify({
    generatedAt: new Date().toISOString(),
    routes: routes.length,
    stops: stops.length,
  })};\n`,
);

writeFileSync(
  join(outDir, "stops.js"),
  `${banner}window.QR_STOPS = ${JSON.stringify(stops)};\n`,
);

const bytes = JSON.stringify(routes).length + JSON.stringify(stops).length;
console.log(
  `export-qr-admin-data: wrote ${routes.length} routes and ${stops.length} stops to qr-admin/data (${Math.round(bytes / 1024)} KB of names).`,
);
