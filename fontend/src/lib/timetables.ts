import dataset from "@/data/kolkata-bus-data.json";

/*
 * Static timetable data layer.
 *
 * Everything the site knows about routes and stops comes from `src/data/kolkata-bus-data.json`,
 * which is generated from the Excel directories by `python manage.py export-static-data`.
 * There are no network calls: all lookups run in the browser on that bundled data.
 *
 * Every departure the site shows is a published run of a verified route. There are deliberately
 * no estimated, sampled or interpolated times: a route whose sheet has no times, or that the
 * transport office has not confirmed yet, is listed as "no timetable yet" and never invents one.
 * Routes with `verified: false` are hidden from journey search entirely.
 */

export type ServiceType = "AC" | "Non-AC";
export type Direction = "outbound" | "return";

export interface RouteStop {
  name: string;
  /** clock time in minutes after midnight, or null when the source publishes no time for this stop */
  minutes: number | null;
  /** true when the stop sits between the searched boarding and alighting stops */
  journey: boolean;
}

export interface BusTrip {
  id: string;
  number: string;
  operator: string;
  type: ServiceType;
  terminusFrom: string;
  terminusTo: string;
  boarding: string;
  alighting: string;
  departure: number;
  arrival: number;
  duration: number;
  via: string[];
  /** every stop on the route in this direction, in order */
  fullStops: RouteStop[];
  /** typical minutes between departures; null when the source has too few runs to say */
  headway: number | null;
  serviceStart: number;
  serviceEnd: number;
  runCode: string | null;
  bus: string | null;
  notes: string | null;
}

export interface TransferPlan {
  id: string;
  from: string;
  to: string;
  transferStop: string;
  first: BusTrip;
  second: BusTrip;
  /** minutes spent waiting at the change stop */
  wait: number;
  departure: number;
  arrival: number;
  duration: number;
}

export interface RouteSummary {
  number: string;
  operator: string;
  type: ServiceType;
  category: string | null;
  origin: string;
  destination: string;
  source: "directory" | "preview";
  /** false = still waiting for the transport office: listed, but with no times */
  verified: boolean;
}

export interface RouteDetail extends RouteSummary {
  stops: string[];
  via: string[];
  fleetText: string | null;
  fleetCount: number | null;
  /** where the published times came from, or null when the route has none */
  timetableSource: string | null;
}

/** A route that physically serves both stops but publishes no times for them. */
export interface ConnectingRoute {
  number: string;
  operator: string;
  type: ServiceType;
  origin: string;
  destination: string;
  verified: boolean;
}

export interface RouteDeparture {
  id: string;
  runCode: string | null;
  bus: string | null;
  departure: number;
  arrival: number;
  notes: string | null;
}

