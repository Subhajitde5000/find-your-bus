/**
 * The generator merges stop names that are the same place ("Esplanade" into
 * "Esplanade Curzon Park"). Older or shorter names still resolve to the kept one.
 */
const MERGED_STOPS = new Map<string, string>();
for (const [canonical, variants] of Object.entries(DATA.meta.dedupe?.mergedStops ?? {})) {
  for (const variant of variants) MERGED_STOPS.set(variant.toLowerCase(), canonical);
}

export function canonicalStop(name: string): string {
  const value = name.trim();
  return MERGED_STOPS.get(value.toLowerCase()) ?? value;
}

/** Aliases re-keyed onto the kept stop name, plus the retired names themselves. */
const ALIASES_BY_STOP: Record<string, string[]> = {};
for (const [key, list] of Object.entries(STOP_ALIASES)) {
  const target = canonicalStop(key);
  ALIASES_BY_STOP[target] = [...(ALIASES_BY_STOP[target] ?? []), ...list, key.toLowerCase()];
}

function normalize(value: string): string {
  return value
    .toLocaleLowerCase()
    .replace(/[^a-z0-9\u0980-\u09ff ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function editDistance(a: string, b: string, max: number): number {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let previous = Array.from({ length: b.length + 1 }, (_, index) => index);
  for (let i = 1; i <= a.length; i += 1) {
    const current = [i];
    let rowMin = i;
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      current[j] = Math.min(previous[j] + 1, current[j - 1] + 1, previous[j - 1] + cost);
      rowMin = Math.min(rowMin, current[j]);
    }
    if (rowMin > max) return max + 1;
    previous = current;
  }
  return previous[b.length];
}

const FUZZY_SCORE = 52;

function scoreName(query: string, candidate: string): number {
  if (candidate === query) return 100;
  if (candidate.startsWith(query)) return 80;
  const words = candidate.split(" ");
  if (words.some((word) => word.startsWith(query))) return 70;
  if (candidate.includes(query)) return 60;
  if (query.length >= 4) {
    const allowed = query.length >= 6 ? 2 : 1;
    if (editDistance(query, candidate, allowed) <= allowed) return FUZZY_SCORE;
    if (words.some((word) => editDistance(query, word, 1) <= 1)) return FUZZY_SCORE;
    if (editDistance(query, candidate.slice(0, query.length), 1) <= 1) return FUZZY_SCORE - 2;
  }
  return 0;
}

const SEARCH_INDEX = STOPS.map((name) => ({
  name,
  names: [name, ...(ALIASES_BY_STOP[name] ?? [])].map(normalize),
}));

/** Typo-tolerant stop search that also understands short names and Bengali spellings. */
export function searchStops(input: string, limit = 7): { name: string; score: number }[] {
  const query = normalize(input);
  if (!query) return STOPS.slice(0, limit).map((name) => ({ name, score: 0 }));
  return SEARCH_INDEX.map((entry) => ({
    name: entry.name,
    score: Math.max(...entry.names.map((candidate) => scoreName(query, candidate))),
  }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || a.name.length - b.name.length || a.name.localeCompare(b.name))
    .slice(0, limit);
}

/** Exact names and aliases always resolve; a single clear one-typo match resolves too. */
export function resolveStop(input: string): string | undefined {
  const results = searchStops(input, 2);
  if (!results.length || normalize(input) === "") return undefined;
  const [best, next] = results;
  if (best.score === 100) return best.name;
  if (best.score === FUZZY_SCORE && (!next || next.score < FUZZY_SCORE)) return best.name;
  return undefined;
}

// ---------------------------------------------------------------- journeys

const DIRECTIONS: Direction[] = ["outbound", "return"];
const MIN_CHANGE_MINUTES = 4;

function stopsInDirection(route: Route, direction: Direction): string[] {
  return direction === "outbound" ? route.stops : [...route.stops].reverse();
}

/** Keeps journeys that cross midnight in order. */
function arrivalAfter(departure: number, arrival: number): number {
  return arrival < departure ? arrival + 1440 : arrival;
}

function scheduledTrips(route: Route, direction: Direction, stops: string[], out: BusTrip[]) {
  const last = stops.length - 1;
  const headway = route.headway[direction];
  const departures = route.scheduled.map((run) => (direction === "outbound" ? run.out : run.ret)[0]);
  const serviceStart = Math.min(...departures);
  const serviceEnd = Math.max(...departures);

  for (const run of route.scheduled) {
    const [departure, rawArrival] = direction === "outbound" ? run.out : run.ret;
    const arrival = arrivalAfter(departure, rawArrival);
    out.push({
      id: `${run.run}-${direction}`,
      number: route.number,
      operator: route.operator,
      type: route.type,
      terminusFrom: stops[0],
      terminusTo: stops[last],
      boarding: stops[0],
      alighting: stops[last],
      departure,
      arrival,
      duration: Math.max(1, arrival - departure),
      via: stops.slice(1, last),
      fullStops: stops.map((name, index) => ({
        name,
        minutes: index === 0 ? departure : index === last ? arrival : null,
        journey: true,
      })),
      headway,
      serviceStart,
      serviceEnd,
      runCode: run.run,
      bus: run.bus,
      notes: run.notes,
    });
  }
}

function tripsOnRoute(route: Route, from: string, to: string): BusTrip[] {
  const found: BusTrip[] = [];
  for (const direction of DIRECTIONS) {
    const stops = stopsInDirection(route, direction);
    const boarding = stops.indexOf(from);
    const alighting = stops.indexOf(to);
    if (boarding < 0 || alighting <= boarding) continue;
    // Times are only published at a route's two terminals, so only a terminal-to-terminal
    // journey has a timetable. Every other pair on the same route is reported as "no
    // timetable yet" instead of being given a made-up departure time.
    const isTerminalPair = boarding === 0 && alighting === stops.length - 1;
    if (!isTerminalPair) continue;
    scheduledTrips(route, direction, stops, found);
  }
  return found;
}

/** Every published bus that passes both stops, in travel order, sorted by departure. */
export function findTrips(from: string, to: string): BusTrip[] {
  const start = canonicalStop(from);
  const end = canonicalStop(to);
  if (!start || !end || start === end) return [];
  const results: BusTrip[] = [];
  // Only routes through the boarding stop can connect the pair. Unverified routes are never
  // offered as journey options.
  for (const route of ROUTES_BY_STOP.get(start) ?? []) {
    if (!route.verified) continue;
    results.push(...tripsOnRoute(route, start, end));
  }
  return results.sort((a, b) => a.departure - b.departure || a.number.localeCompare(b.number));
}

/**
 * Confirmed routes that pass both stops but publish no times for them, so the site can say
 * "this route connects your stops — no timetable yet" instead of showing invented times.
 */
export function findRoutesWithoutTimetable(from: string, to: string): ConnectingRoute[] {
  const start = canonicalStop(from);
  const end = canonicalStop(to);
  if (!start || !end || start === end) return [];
  const found: ConnectingRoute[] = [];
  for (const route of ROUTES_BY_STOP.get(start) ?? []) {
    if (!route.verified || route.scheduled.length === 0) continue;
    const connects = DIRECTIONS.some((direction) => {
      const stops = stopsInDirection(route, direction);
      const boarding = stops.indexOf(start);
      const alighting = stops.indexOf(end);
      return boarding >= 0 && alighting > boarding;
    });
    if (!connects) continue;
    if (tripsOnRoute(route, start, end).length) continue;
    found.push({
      number: route.number,
      operator: route.operator,
      type: route.type,
      origin: route.origin,
      destination: route.destination,
      verified: route.verified,
    });
  }
  return found.sort((a, b) => a.number.localeCompare(b.number));
}

/**
 * How many routes serve both stops in order but are still waiting for the transport office.
 * Journey search never lists them (unconfirmed corridors are not offered as a journey), but the
 * empty state says that they exist instead of pretending no route runs there.
 */
export function countUnconfirmedRoutes(from: string, to: string): number {
  const start = canonicalStop(from);
  const end = canonicalStop(to);
  if (!start || !end || start === end) return 0;
  let count = 0;
  for (const route of ROUTES_BY_STOP.get(start) ?? []) {
    if (route.verified) continue;
    const connects = DIRECTIONS.some((direction) => {
      const stops = stopsInDirection(route, direction);
      const boarding = stops.indexOf(start);
      const alighting = stops.indexOf(end);
      return boarding >= 0 && alighting > boarding;
    });
    if (connects) count += 1;
  }
  return count;
}

/** Looks a saved bus back up from a previously viewed journey. */
export function findTrip(from: string, to: string, tripId: string): BusTrip | undefined {
  return findTrips(from, to).find((trip) => trip.id === tripId);
}

/** One-change journeys for pairs with no direct bus. */
export function findTransferPlans(from: string, to: string, afterMinute: number, limit = 5): TransferPlan[] {
  if (!from || !to || from === to) return [];
  const plans: TransferPlan[] = [];
  // A change is only possible at a stop served from both ends; other stops can
  // never produce a plan, so they are not searched.
  // Only verified routes can carry a leg of the plan, so only they widen the reachable sets.
  const reachableFromStart = new Set<string>();
  for (const route of ROUTES_BY_STOP.get(from) ?? []) {
    if (!route.verified) continue;
    for (const stop of route.stops) reachableFromStart.add(stop);
  }
  const reachableToEnd = new Set<string>();
  for (const route of ROUTES_BY_STOP.get(to) ?? []) {
    if (!route.verified) continue;
    for (const stop of route.stops) reachableToEnd.add(stop);
  }
  for (const stop of STOPS) {
    if (stop === from || stop === to) continue;
    if (!reachableFromStart.has(stop) || !reachableToEnd.has(stop)) continue;
    const legOne = findTrips(from, stop).filter((trip) => trip.departure >= afterMinute);
    if (!legOne.length) continue;
    const legTwo = findTrips(stop, to);
    if (!legTwo.length) continue;
    for (const first of legOne.slice(0, 12)) {
      const second = legTwo.find(
        (trip) => trip.departure >= first.arrival + MIN_CHANGE_MINUTES && trip.number !== first.number,
      );
      if (!second) continue;
      plans.push({
        id: `${first.id}>${second.id}`,
        from,
        to,
        transferStop: stop,
        first,
        second,
        wait: second.departure - first.arrival,
        departure: first.departure,
        arrival: second.arrival,
        duration: second.arrival - first.departure,
      });
      break;
    }
  }
  const seen = new Set<string>();
  return plans
    .sort((a, b) => a.arrival - b.arrival || a.duration - b.duration)
    .filter((plan) => {
      const key = `${plan.first.number}>${plan.second.number}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .slice(0, limit);
}

// ---------------------------------------------------------------- routes

function toSummary(route: Route): RouteSummary {
  return {
    number: route.number,
    operator: route.operator,
    type: route.type,
    category: route.category,
    origin: route.origin,
    destination: route.destination,
    source: route.source,
    verified: route.verified,
  };
}

/**
 * Route number, origin or destination matches. Exact route numbers come first, then prefixes.
 * An empty query returns the first routes of the directory.
 */
export function searchRoutes(query: string, limit = 10): RouteSummary[] {
  const q = query.trim().toLowerCase();
  if (!q) return ROUTES.slice(0, limit).map(toSummary);
  const rank = (route: Route) => {
    const number = route.number.toLowerCase();
    if (number === q) return 0;
    if (number.startsWith(q)) return 1;
    return 2;
  };
  return ROUTES.filter(
    (route) =>
      route.number.toLowerCase().includes(q) ||
      route.origin.toLowerCase().includes(q) ||
      route.destination.toLowerCase().includes(q),
  )
    .sort((a, b) => rank(a) - rank(b))
    .slice(0, limit)
    .map(toSummary);
}

export function getRoute(routeNumber: string): RouteDetail | undefined {
  const route = ROUTE_BY_NUMBER.get(routeNumber.trim().toLowerCase());
  if (!route) return undefined;
  return {
    ...toSummary(route),
    stops: route.stops,
    via: route.stops.slice(1, -1),
    fleetText: route.fleetText,
    fleetCount: route.fleetCount,
    timetableSource: route.timetableSource,
  };
}

/** Departures from the first stop of a direction, for the route timetable table. */
export function getRouteDepartures(routeNumber: string, direction: Direction): RouteDeparture[] {
  const route = ROUTE_BY_NUMBER.get(routeNumber.trim().toLowerCase());
  if (!route) return [];

  // Only runs printed in the workbook are listed. A route with no published runs returns an
  // empty list, and the UI says so rather than filling the table with invented times.
  return route.scheduled
    .map((run) => {
      const [departure, rawArrival] = direction === "outbound" ? run.out : run.ret;
      return {
        id: `${run.run}-${direction}`,
        runCode: run.run,
        bus: run.bus,
        departure,
        arrival: arrivalAfter(departure, rawArrival),
        notes: run.notes,
      };
    })
    .sort((a, b) => a.departure - b.departure);
}

