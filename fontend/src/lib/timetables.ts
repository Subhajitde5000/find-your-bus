// ---------------------------------------------------------------- time helpers

export function parseClock(value: string): number {
  if (value.length === 5 && value.charCodeAt(2) === 58) {
    return (
      ((value.charCodeAt(0) - 48) * 10 + (value.charCodeAt(1) - 48)) * 60 +
      (value.charCodeAt(3) - 48) * 10 +
      (value.charCodeAt(4) - 48)
    );
  }
  const [hours, minutes] = value.split(":").map(Number);
  return hours * 60 + minutes;
}

export function formatClock(totalMinutes: number): { time: string; period: string } {
  const minutesInDay = ((totalMinutes % 1440) + 1440) % 1440;
  const hours = Math.floor(minutesInDay / 60);
  const minutes = minutesInDay % 60;
  return {
    time: `${String(hours % 12 || 12).padStart(2, "0")}:${String(minutes).padStart(2, "0")}`,
    period: hours < 12 ? "AM" : "PM",
  };
}

/** 24-hour "HH:MM" for inputs and sample data. */
export function toClock24(totalMinutes: number): string {
  const minutesInDay = ((totalMinutes % 1440) + 1440) % 1440;
  return `${String(Math.floor(minutesInDay / 60)).padStart(2, "0")}:${String(minutesInDay % 60).padStart(2, "0")}`;
}

export function formatDuration(minutes: number): string {
  const hours = Math.floor(minutes / 60);
  const remaining = minutes % 60;
  return hours ? `${hours} hr${remaining ? ` ${remaining} min` : ""}` : `${remaining} min`;
}

// ---------------------------------------------------------------- normalised route model

interface ScheduledRun {
  run: string;
  direction: Direction;
  bus: string | null;
  notes: string | null;
  /** published minutes at each stop, in the direction's travel order; null where blank */
  times: (number | null)[];
  /**
   * The same times unwrapped onto a service timeline. A run that leaves after 23:00 and reaches a
   * stop after midnight keeps counting past 1440, so durations and waits stay positive. Runs are
   * processed in the order the workbook lists them, so an overnight service that publishes 22:15,
   * 23:15, 00:15, 01:15 also keeps its runs in chronological order.
   */
  timeline: (number | null)[];
}

interface Route {
  number: string;
  source: RouteSource;
  provenance: string | null;
  confidence: string | null;
  operator: string;
  category: string | null;
  type: ServiceType;
  origin: string;
  destination: string;
  stops: string[];
  returnStops: string[];
  outboundIndex: Map<string, number>;
  returnIndex: Map<string, number>;
  fleetText: string | null;
  fleetCount: number | null;
  scheduled: ScheduledRun[];
  outboundRuns: ScheduledRun[];
  returnRuns: ScheduledRun[];
  /**
   * Sample route timings. `reverseOffset` is the sample turnaround at the far terminal:
   * the same bus comes back after its outbound travel time plus this many minutes.
   */
  frequency: { first: number; last: number; every: number; reverseOffset: number; legs: number[] } | null;
}

/** Average minutes between the first and last run; null with fewer than two runs. */
function typicalHeadway(departures: number[]): number | null {
  if (departures.length < 2) return null;
  const sorted = [...departures].sort((a, b) => a - b);
  return Math.round((sorted[sorted.length - 1] - sorted[0]) / (sorted.length - 1));
}

function normaliseRoute(raw: RawRoute): Route {
  const bus = (index: number | null) => (index === null ? null : DATA.buses[index] ?? null);
  const previousFirst: Record<Direction, number | null> = { outbound: null, return: null };
  const scheduled: ScheduledRun[] = raw.runs.map((run) => {
    let previous: number | null = null;
    const timeline: (number | null)[] = run.times.map((value) => {
      if (value === null) return null;
      let minutes = parseClock(value);
      while (previous !== null && minutes < previous) minutes += 1440;
      previous = minutes;
      return minutes;
    });
    const first = timeline.find((value): value is number => value !== null);
    if (first !== undefined) {
      const lastFirst = previousFirst[run.direction];
      // A run after midnight follows the late-evening runs of the same service day. A small
      // out-of-order value is left alone; only a real overnight jump gets a 24-hour offset.
      if (lastFirst !== null && first < lastFirst - 720) {
        const bump = Math.ceil((lastFirst - first) / 1440) * 1440;
        for (let index = 0; index < timeline.length; index += 1) {
          const value = timeline[index];
          if (value !== null) timeline[index] = value + bump;
        }
      }
      previousFirst[run.direction] = timeline.find((value): value is number => value !== null) ?? null;
    }
    return {
      run: run.run,
      direction: run.direction,
      bus: bus(run.bus),
      notes: run.notes,
      times: run.times.map((value) => (value === null ? null : parseClock(value))),
      timeline,
    };
  });
  const returnStops = [...raw.stops].reverse();
  const outboundIndex = new Map<string, number>();
  for (let i = 0; i < raw.stops.length; i += 1) outboundIndex.set(raw.stops[i], i);
  const returnIndex = new Map<string, number>();
  for (let i = 0; i < returnStops.length; i += 1) returnIndex.set(returnStops[i], i);
  return {
    number: raw.number,
    source: raw.source,
    provenance: raw.provenance ?? null,
    confidence: raw.confidence ?? null,
    operator: raw.operator,
    category: raw.category,
    type: raw.type,
    origin: raw.origin,
    destination: raw.destination,
    stops: raw.stops,
    returnStops,
    outboundIndex,
    returnIndex,
    fleetText: raw.fleet?.text ?? null,
    fleetCount: raw.fleet?.count ?? null,
    scheduled,
    outboundRuns: scheduled.filter((run) => run.direction === "outbound"),
    returnRuns: scheduled.filter((run) => run.direction === "return"),
    frequency: raw.frequency
      ? {
          first: parseClock(raw.frequency.first),
          last: parseClock(raw.frequency.last),
          every: raw.frequency.every,
          reverseOffset: raw.frequency.reverseOffset,
          legs: raw.frequency.legs,
        }
      : null,
  };
}

const ROUTES: Route[] = DATA.routes.map(normaliseRoute);
const ROUTE_BY_NUMBER = new Map(ROUTES.map((route) => [route.number.toLowerCase(), route]));

/**
 * Stop -> routes serving it, in directory order. Journey search only ever needs the
 * routes through the boarding stop, so this keeps lookups fast as the directory grows.
 */
const ROUTES_BY_STOP = new Map<string, Route[]>();
for (const route of ROUTES) {
  for (const stop of route.stops) {
    const serving = ROUTES_BY_STOP.get(stop);
    if (serving) serving.push(route);
    else ROUTES_BY_STOP.set(stop, [route]);
  }
}

