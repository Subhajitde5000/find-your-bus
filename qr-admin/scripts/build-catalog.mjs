#!/usr/bin/env node
/**
 * Write qr-admin/data/catalog.js from the website's own dataset.
 *
 * The sticker maker must offer exactly the routes and stops the app knows, or a printed
 * sticker would name something that does not exist. The single source is
 * `fontend/src/data/kolkata-bus-data.json`, the same file the site bundles.
 *
 * The output is a plain script that assigns `window.KONBUS_QR_CATALOG`, not JSON: this
 * tool is opened by double-clicking index.html, and browsers block `fetch()` on
 * file:// URLs. A script tag has no such problem, so the tool needs no server at all.
 *
 * Run from the repository root:
 *
 *   node qr-admin/scripts/build-catalog.mjs
 *
 * Re-run it whenever the data changes, and commit the result.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const SOURCE = join(ROOT, "fontend/src/data/kolkata-bus-data.json");
const OUT = join(ROOT, "qr-admin/data/catalog.js");

const dataset = JSON.parse(readFileSync(SOURCE, "utf8"));
const byNumber = (a, b) => a.localeCompare(b, "en", { numeric: true, sensitivity: "base" });

const routes = (dataset.routes ?? [])
  .map((route) => ({
    number: route.number,
    type: route.type ?? "Non-AC",
    operator: route.operator ?? "",
    origin: route.origin,
    destination: route.destination,
    stops: Array.isArray(route.stops) ? route.stops.length : 0,
    timed: Boolean((route.runs && route.runs.length) || route.frequency),
  }))
  .sort((a, b) => byNumber(a.number, b.number));

const stops = (dataset.stops ?? [])
  .map((stop) => ({ name: stop.name }))
  .sort((a, b) => a.name.localeCompare(b.name));

const payload = {
  generated: new Date().toISOString().slice(0, 10),
  source: "fontend/src/data/kolkata-bus-data.json",
  counts: { routes: routes.length, stops: stops.length },
  routes,
  stops,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `/* Generated by qr-admin/scripts/build-catalog.mjs -- do not edit by hand. */\n` +
    `/* Source: ${payload.source} (${payload.generated}) */\n` +
    `window.KONBUS_QR_CATALOG = ${JSON.stringify(payload)};\n`,
  "utf8",
);

console.log(`build-catalog: wrote ${routes.length} routes and ${stops.length} stops to qr-admin/data/catalog.js`);
