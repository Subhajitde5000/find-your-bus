#!/usr/bin/env python3
"""
Write `data/Kolkata_Bus_Routes_Extension-v3.xlsx` from `data/external-routes.json`.

The v2 workbook stays exactly as published.  This companion workbook holds the routes
that the v2 directory does not contain:

* `Route Catalogue` - every route number, operator, class, termini and full stop chain
  from the WBTC city route list and the Bus-O-Pedia private/government catalogue.  No
  time is written, because neither source publishes one.
* one `Timed_*` sheet per long-distance service whose operator or depot publishes a
  time at every stop.  The time columns are copied, never computed.
* `README` - provenance, licence notes and the rules used to merge the two lists.

Nothing in this file is derived from the v2 workbook.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

import openpyxl
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "data/external-routes.json"
DEFAULT_OUTPUT = ROOT / "data/Kolkata_Bus_Routes_Extension-v3.xlsx"

HEADER_FILL = PatternFill("solid", fgColor="1F4E3D")
HEADER_FONT = Font(color="FFFFFF", bold=True)
TITLE_FONT = Font(size=14, bold=True)
WRAP = Alignment(wrap_text=True, vertical="top")


def safe_title(value: str, used: set[str]) -> str:
    base = re.sub(r"[^A-Za-z0-9 _-]", "", value).strip() or "Timed"
    base = f"Timed_{base}"[:31]
    title = base
    suffix = 2
    while title in used:
        title = f"{base[:28]}_{suffix}"
        suffix += 1
    used.add(title)
    return title


def header(ws: Any, row: int, values: list[str]) -> None:
    for column, value in enumerate(values, start=1):
        cell = ws.cell(row=row, column=column, value=value)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center")


def write_readme(ws: Any, payload: dict[str, Any]) -> None:
    ws.column_dimensions["A"].width = 26
    ws.column_dimensions["B"].width = 110
    rows = [
        ("Kolkata Bus Routes Extension v3", ""),
        ("", ""),
        ("What this workbook is", "Routes that are missing from Kolkata_Comprehensive_Bus_Routes_and_Fleet_Directory-v2.xlsx: every route line published by WBTC and by the Bus-O-Pedia private/government catalogue that the v2 directory does not already contain."),
        ("", ""),
        ("Route facts", "arkodeepg/calcutta-transport data/bus (MIT code, ODbL data). Route numbers, termini and stop order come from WBTC's own city route list (https://wbtconline.in/wbtc-city-bus-routes) and Kolkata Bus-O-Pedia (https://www.kolbusopedia.com/bus-routes and /bus-routes-government), with OpenStreetMap for fifteen OSM-only numbers."),
        ("", ""),
        ("Timetables", "murmusuvash2-wq/busjatri-open-data (CC BY 4.0), which transcribes operator and depot timetables. Only services with a published time at EVERY stop in at least one direction are written here. A service whose times are blank at a stop is not included."),
        ("", ""),
        ("What is deliberately absent", "Kolkata city buses run to frequency. WBTC's list has no times; BusJatri states its city stop times are estimated from trip departure + route length; citybustimetable.com states the same. None of those estimates is used. The Route Catalogue therefore has no time columns at all."),
        ("", ""),
        ("Duplicates", "A route already in v2 is not repeated. When a number exists in v2 but means a different route, the new route is written with its termini in the number, e.g. '15 (Ultadanga - Howrah Railway Station)'."),
        ("", ""),
        ("Counts", f"{payload['meta']['counts']['routeOnly']} catalogue routes, {payload['meta']['counts']['timed']} timed services."),
        ("", ""),
        ("Generated by", "scripts/build_extension_workbook.py from data/external-routes.json."),
    ]
    for index, (label, text) in enumerate(rows, start=1):
        ws.cell(row=index, column=1, value=label).font = TITLE_FONT if index == 1 else Font(bold=True)
        cell = ws.cell(row=index, column=2, value=text)
        cell.alignment = WRAP


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    payload = json.loads(args.source.read_text(encoding="utf-8"))
    routes = payload["routes"]
    catalogue = [route for route in routes if route["kind"] == "route-only"]
    timed = [route for route in routes if route["kind"] == "timed"]

    wb = openpyxl.Workbook()
    readme = wb.active
    readme.title = "README"
    write_readme(readme, payload)

    ws = wb.create_sheet("Route Catalogue")
    header(
        ws,
        row=1,
        values=["Route No", "Operator", "Class", "Origin", "Destination", "Stops (travel order)", "Source", "Confidence", "Notes"],
    )
    for row_index, route in enumerate(sorted(catalogue, key=lambda item: item["number"].lower()), start=2):
        values = [
            route["number"],
            route["operator"],
            route["mode"],
            route["origin"],
            route["destination"],
            " > ".join(route["stops"]),
            route["source"],
            route["confidence"],
            route.get("notes") or "",
        ]
        for column, value in enumerate(values, start=1):
            cell = ws.cell(row=row_index, column=column, value=value)
            cell.alignment = WRAP
    widths = {"A": 34, "B": 18, "C": 9, "D": 24, "E": 24, "F": 90, "G": 24, "H": 12, "I": 46}
    for column, width in widths.items():
        ws.column_dimensions[column].width = width
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:I{max(1, len(catalogue) + 1)}"

    used = {readme.title, ws.title}
    for route in timed:
        title = safe_title(route["number"], used)
        sheet = wb.create_sheet(title)
        sheet.column_dimensions["A"].width = 7
        sheet.column_dimensions["B"].width = 36
        sheet.column_dimensions["C"].width = 15
        sheet.column_dimensions["D"].width = 15
        meta_rows = [
            ("Service", route["number"]),
            ("Operator", route["operator"]),
            ("Registration", route.get("reg_no") or ""),
            ("Bus type", route.get("notes") or ""),
            ("Origin", route["origin"]),
            ("Destination", route["destination"]),
            ("Fare", route.get("fare") or ""),
            ("Source", route.get("source") or ""),
            ("Detail", route.get("detail_url") or ""),
        ]
        for index, (label, value) in enumerate(meta_rows, start=1):
            sheet.cell(row=index, column=1, value=label).font = Font(bold=True)
            sheet.cell(row=index, column=2, value=value)
        header(sheet, row=len(meta_rows) + 2, values=["#", "Stoppage", "Up time", "Down time"])
        outbound = next((run for run in route["runs"] if run["direction"] == "outbound"), None)
        return_run = next((run for run in route["runs"] if run["direction"] == "return"), None)
        down = list(reversed(return_run["times"])) if return_run else []
        for index, stop in enumerate(route["stops"]):
            row = len(meta_rows) + 3 + index
            sheet.cell(row=row, column=1, value=index + 1)
            sheet.cell(row=row, column=2, value=stop)
            sheet.cell(row=row, column=3, value=outbound["times"][index] if outbound else "")
            sheet.cell(row=row, column=4, value=down[index] if down else "")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    wb.save(args.output)
    print(f"Wrote {args.output}: {len(catalogue)} catalogue routes, {len(timed)} timed services, {len(wb.sheetnames)} sheets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
